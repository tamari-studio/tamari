CREATE OR REPLACE FUNCTION miso.move_tab(p_tab uuid, p_space text)
 RETURNS miso.tabs
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare
  v_tab miso.tabs;
  v_existing miso.tabs;
begin
  select * into v_tab from miso.tabs where id = p_tab for update;
  if not found then
    raise exception 'tab % not found', p_tab using errcode = 'P0002';
  end if;
  if v_tab.space_id = p_space then
    return v_tab;
  end if;
  select * into v_existing from miso.tabs where space_id = p_space and ref = v_tab.ref;
  if found then
    delete from miso.tabs where id = p_tab;
    return v_existing;
  end if;
  update miso.tabs
     set space_id = p_space,
         position = coalesce((select max(t.position) from miso.tabs t where t.space_id = p_space), 0) + 1
   where id = p_tab
  returning * into v_tab;
  return v_tab;
end
$function$;

CREATE OR REPLACE FUNCTION miso.move_widget(p_from text, p_to text, p_ref text)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare
  v_target jsonb;
begin
  if p_from = p_to then
    return;
  end if;
  insert into miso.space_layouts (space_id) values (p_from), (p_to) on conflict (space_id) do nothing;
  perform 1 from miso.space_layouts where space_id in (p_from, p_to) order by space_id for update;
  update miso.space_layouts
     set widgets = coalesce(
       (select jsonb_agg(w) from jsonb_array_elements(widgets) w where w->>'ref' <> p_ref),
       '[]'::jsonb)
   where space_id = p_from;
  select widgets into v_target from miso.space_layouts where space_id = p_to;
  if not exists (select 1 from jsonb_array_elements(v_target) w where w->>'ref' = p_ref) then
    update miso.space_layouts set widgets = v_target || jsonb_build_array(jsonb_build_object('ref', p_ref))
     where space_id = p_to;
  end if;
  insert into miso.tabs (space_id, ref, position) values (p_to, 'widgets', -1)
    on conflict (space_id, ref) do nothing;
end
$function$;

CREATE OR REPLACE FUNCTION miso.set_connector_secret(p_connector uuid, p_secret jsonb)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_secret_id uuid;
begin
  if not miso.is_service() then
    raise exception 'only the miso service account can write connector secrets' using errcode = '42501';
  end if;
  if jsonb_typeof(p_secret) <> 'object' then
    raise exception 'connector secret must be a JSON object';
  end if;
  select secret_id into v_secret_id from miso.connectors where id = p_connector;
  if not found then
    raise exception 'connector % not found', p_connector using errcode = 'P0002';
  end if;
  if v_secret_id is null then
    v_secret_id := vault.create_secret(p_secret::text, 'miso.connector.' || p_connector::text, 'miso connector env values');
    update miso.connectors set secret_id = v_secret_id where id = p_connector;
  else
    perform vault.update_secret(v_secret_id, p_secret::text);
    update miso.connectors set updated_at = now() where id = p_connector;
  end if;
end
$function$;

