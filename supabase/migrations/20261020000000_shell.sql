CREATE OR REPLACE FUNCTION app.app_user_bootstrap()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    is_first_user  boolean;
    allowed_domain boolean;
    name          text := coalesce(NEW.raw_user_meta_data ->> 'full_name', NEW.raw_user_meta_data ->> 'name');
BEGIN
    -- The app's own service accounts (scripts/supabase-setup.ts) are not people. Auth writes
    -- app_metadata after this insert, so the flag is read from user_metadata. Anyone could set it
    -- on their own sign-up, but it only takes away: no tier, never the owner.
    IF coalesce(NEW.raw_user_meta_data ->> 'miso_service', '') = 'true' THEN
        RETURN NEW;
    END IF;

    LOCK TABLE app.app_user IN SHARE ROW EXCLUSIVE MODE;

    is_first_user := NOT EXISTS (SELECT 1 FROM app.app_user);
    allowed_domain := EXISTS (
        SELECT 1 FROM miso.allowed_domains d
         WHERE d.domain = lower(split_part(NEW.email, '@', 2))
    );

    IF is_first_user THEN
        INSERT INTO app.app_user (user_id, email, display_name, tier, status)
        VALUES (NEW.id, NEW.email, name, 'owner'::app.tier, 'active');

        INSERT INTO app.tier_change (user_id, from_tier, to_tier, changed_by, reason)
        VALUES (NEW.id, NULL, 'owner'::app.tier, NEW.id, 'first user bootstrap');
    ELSIF allowed_domain THEN
        INSERT INTO app.app_user (user_id, email, display_name, tier, status)
        VALUES (NEW.id, NEW.email, name, 'member'::app.tier, 'active');

        INSERT INTO app.tier_change (user_id, from_tier, to_tier, changed_by, reason)
        VALUES (NEW.id, NULL, 'member'::app.tier, NEW.id, 'member by default at sign-up');
    ELSE
        INSERT INTO app.app_user (user_id, email, display_name, tier, status)
        VALUES (NEW.id, NEW.email, name, NULL, 'pending');
    END IF;

    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION app.app_user_guard_last_owner()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    removes_ownership boolean;
    verb              text;
BEGIN
    -- NEW is unassigned in a DELETE trigger and SQL's OR does not short
    -- circuit, so the two cases are branched rather than combined.
    IF TG_OP = 'DELETE' THEN
        removes_ownership := true;
        verb := 'deletion';
    ELSE
        removes_ownership := NEW.tier IS DISTINCT FROM 'owner'::app.tier
                          OR NEW.status IS DISTINCT FROM 'active';
        verb := 'demotion or suspension';
    END IF;

    IF OLD.tier = 'owner'::app.tier
       AND OLD.status = 'active'
       AND removes_ownership
       AND NOT EXISTS (
            SELECT 1
              FROM app.app_user o
             WHERE o.user_id <> OLD.user_id
               AND o.tier = 'owner'::app.tier
               AND o.status = 'active'
       )
    THEN
        RAISE EXCEPTION
            'last-owner invariant: % of the only active owner is refused -- at least one active owner must exist at all times',
            verb
            USING HINT = 'Grant owner to another active user first, then change this row.';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION app.app_user_log_tier_change()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    actor uuid;
BEGIN
    IF NEW.tier IS NOT DISTINCT FROM OLD.tier THEN
        RETURN NEW;
    END IF;

    actor := coalesce(
        auth.uid(),
        nullif(current_setting('app.actor_id', true), '')::uuid
    );

    IF actor IS NULL THEN
        RAISE EXCEPTION
            'unattributable tier change: app.tier_change requires an actor and there is no authenticated identity'
            USING HINT = 'From a direct SQL connection: SET LOCAL app.actor_id = ''<app_user.user_id>''; before the UPDATE.';
    END IF;

    INSERT INTO app.tier_change (user_id, from_tier, to_tier, changed_by, reason)
    VALUES (
        NEW.user_id,
        OLD.tier,
        NEW.tier,
        actor,
        nullif(current_setting('app.change_reason', true), '')
    );

    RETURN NEW;
END;
$function$;

