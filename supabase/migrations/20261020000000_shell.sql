CREATE OR REPLACE FUNCTION app.member_erase(p_user uuid)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_caller uuid := auth.uid();
    v_target app.app_user%ROWTYPE;
BEGIN
    IF v_caller IS NULL OR NOT app.has_at_least('admin'::app.tier) THEN
        RAISE EXCEPTION 'Only admins and owners can delete members.' USING ERRCODE = '42501';
    END IF;
    IF p_user IS NULL THEN
        RAISE EXCEPTION 'Say whom to delete.' USING ERRCODE = '22004';
    END IF;
    IF p_user = v_caller THEN
        RAISE EXCEPTION 'You can''t delete yourself.' USING ERRCODE = '42501';
    END IF;

    -- One deletion at a time, so two owners deleting each other at once can't leave no owner:
    -- the second waits, then the last-owner guard sees the first one's result.
    PERFORM pg_advisory_xact_lock(hashtext('app.member_erase'));

    SELECT * INTO v_target FROM app.app_user u WHERE u.user_id = p_user FOR UPDATE;
    IF NOT FOUND THEN
        RETURN false;
    END IF;

    IF v_target.tier = 'owner'::app.tier AND app.current_tier() IS DISTINCT FROM 'owner'::app.tier THEN
        RAISE EXCEPTION 'Only an owner can delete an owner.' USING ERRCODE = '42501';
    END IF;
    IF EXISTS (SELECT 1 FROM miso.members m WHERE m.user_id = p_user AND m.role = 'service')
    THEN
        RAISE EXCEPTION 'A service account the hosted app depends on.' USING ERRCODE = '42501';
    END IF;

    INSERT INTO app.tier_change (user_id, from_tier, to_tier, changed_by, reason)
    VALUES (p_user, v_target.tier, NULL, v_caller, 'account deleted');

    DELETE FROM auth.users WHERE id = p_user;
    RETURN FOUND;
END;
$function$;

