-- The miso schema: everything the app keeps in Supabase.
--
--   app.app_user, app.tier, ...   people and their tiers (owner > admin > manager > member).
--                                 The first person to sign up becomes the owner; later sign-ups
--                                 wait as 'pending' until an admin approves them on the Members
--                                 page, unless their email domain is in miso.allowed_domains.
--   miso.spaces, tabs, space_layouts   which spaces exist, their tabs and widget grids
--   miso.space_access             which tiers see a space (the Space access page)
--   miso.connectors               env values for space code; secrets live in Vault
--   miso.records                  shared records (@miso/store)
--   miso.feedback                 the Feedback button
--   app.user_activity             last active (Members page, owners only)
--
-- Two service accounts (scripts/supabase-setup.ts creates them): one that space code runs as
-- (a plain member), and the vault account (role 'service') that alone reads secrets.
--
-- In the dashboard, add `miso` and `app` to Settings > API > Exposed schemas
-- (supabase/config.toml does it for the local stack).

create schema if not exists app;
create schema if not exists miso;

create type app.tier as enum ('owner', 'admin', 'manager', 'member');

