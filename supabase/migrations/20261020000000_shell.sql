CREATE OR REPLACE FUNCTION miso.feedback_stamp()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_uid uuid := auth.uid();
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.submitted_by := v_uid;
        NEW.submitter_email := (SELECT u.email FROM auth.users u WHERE u.id = v_uid);
        NEW.submitter_name := (SELECT a.display_name FROM app.app_user a WHERE a.user_id = v_uid);
        NEW.created_at := now();
        NEW.completed_at := NULL;
        NEW.completed_by := NULL;
        NEW.completed_by_email := NULL;
    ELSIF NEW.completed_at IS DISTINCT FROM OLD.completed_at THEN
        IF NEW.completed_at IS NULL THEN
            NEW.completed_by := NULL;
            NEW.completed_by_email := NULL;
        ELSIF OLD.completed_at IS NULL THEN
            NEW.completed_at := now();
            NEW.completed_by := v_uid;
            NEW.completed_by_email := (SELECT u.email FROM auth.users u WHERE u.id = v_uid);
        ELSE
            -- Ticking an issue that is already completed keeps the first tick.
            NEW.completed_at := OLD.completed_at;
        END IF;
    END IF;
    RETURN NEW;
END
$function$;

