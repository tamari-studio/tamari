CREATE OR REPLACE FUNCTION miso.connector_secret_keys()
 RETURNS TABLE(connector_id uuid, keys text[])
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if not miso.is_member() then
    raise exception 'not a miso member' using errcode = '42501';
  end if;
  return query
    select c.id,
           coalesce(
             (select array_agg(k order by k)
                from jsonb_each_text(s.decrypted_secret::jsonb) as e(k, v)
               where coalesce(v, '') <> ''),
             '{}'
           )
    from miso.connectors c
    join vault.decrypted_secrets s on s.id = c.secret_id;
end
$function$;

